export function getExerciseById(id) {
  return EXERCISES.find((e) => e.exercise_id === id || e.id === id) || null;
}

export function getExercisesByPattern(pattern) {
  return EXERCISES.filter((e) => e.movement_pattern === pattern || e.movementPattern === pattern);
}

export function getExercisesByMuscle(muscle) {
  return EXERCISES.filter((e) =>
    (e.primary_muscles || []).includes(muscle) || (e.secondary_muscles || []).includes(muscle)
  );
}

export function resolveEquipmentPreset(presetOrList) {
  if (Array.isArray(presetOrList)) return presetOrList;
  if (typeof presetOrList === "string" && EQUIPMENT_PRESETS[presetOrList]) {
    return EQUIPMENT_PRESETS[presetOrList];
  }
  return EQUIPMENT_PRESETS.full_gym;
}
